/**
 * Regenerates src/brandLogos.ts from assets/brand-logos/*.svg (Simple Icons,
 * 24x24 single-path, brand fill on the <svg> element).
 *
 * Run from packages/ui: node scripts/gen-brand-logos.js
 */
/* global __dirname */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const dir = path.join(root, "assets", "brand-logos");
const ids = {
  tiktok: "tiktok.svg",
  instagram: "instagram.svg",
  chrome: "googlechrome.svg",
  snapchat: "snapchat.svg",
  roblox: "roblox.svg",
  whatsapp: "whatsapp.svg",
  x: "x.svg",
  facebook: "facebook.svg",
  messages: "messages.svg",
};

let out =
  "/**\n" +
  " * Official brand marks (Simple Icons, 24x24 single path) in each brand's color.\n" +
  " * Generated by scripts/gen-brand-logos.js from assets/brand-logos/*.svg — do not hand-edit paths.\n" +
  " */\n\n" +
  "export type BrandLogo = { fill: string; d: string };\n\n" +
  "export const BRAND_LOGOS = {\n";

for (const [id, file] of Object.entries(ids)) {
  const s = fs.readFileSync(path.join(dir, file), "utf8");
  const fill = s.match(/fill="([^"]+)"/)[1];
  const d = s.match(/<path d="([^"]+)"/)[1];
  out += `  ${JSON.stringify(id)}: {\n    fill: ${JSON.stringify(fill)},\n    d: ${JSON.stringify(d)},\n  },\n`;
}

out +=
  "} as const satisfies Record<string, BrandLogo>;\n\n" +
  "export type BrandLogoId = keyof typeof BRAND_LOGOS;\n";

fs.writeFileSync(path.join(root, "src", "brandLogos.ts"), out);
console.log("wrote src/brandLogos.ts");
